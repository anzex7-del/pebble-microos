#!/usr/bin/env python3
"""Validate a pet profile and emit safe compile-time firmware defaults."""
import argparse
import json
import os
from pathlib import Path
import re

THEMES = ("moss", "sky", "peach", "lilac")
EYES = ("round", "sleepy", "pixel")

def validate(p):
    if not isinstance(p, dict) or set(p) != {"schemaVersion", "name", "theme", "eyes", "focusMinutes"}:
        raise ValueError("Expected exactly schemaVersion, name, theme, eyes and focusMinutes.")
    if type(p["schemaVersion"]) is not int or p["schemaVersion"] != 1:
        raise ValueError("Unsupported profile version.")
    if not isinstance(p["name"], str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 _-]{0,15}", p["name"]) or p["name"] != p["name"].strip():
        raise ValueError("Name: 1–16 ASCII letters, numbers, spaces, hyphens or underscores; begin with a letter/number.")
    if p["theme"] not in THEMES or p["eyes"] not in EYES:
        raise ValueError("Unknown theme or eye style.")
    if type(p["focusMinutes"]) is not int or not 5 <= p["focusMinutes"] <= 60:
        raise ValueError("Focus duration must be a whole number from 5 to 60 minutes.")
    return p

def header(p):
    validate(p)
    return f'''#ifndef PEBBLE_PROFILE_H
#define PEBBLE_PROFILE_H
/* Generated by tools/apply_profile.py; not a flashable file. */
#define PB_PET_NAME {json.dumps(p["name"])}
#define PB_DEFAULT_THEME {THEMES.index(p["theme"])}
#define PB_EYE_STYLE {EYES.index(p["eyes"])}
#define PB_FOCUS_MINUTES {p["focusMinutes"]}
#define PB_FIRMWARE_VERSION "0.3.0-preview.1"
#endif
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profile", nargs="?", type=Path)
    parser.add_argument("--from-env", action="store_true", help="Read PEBBLE_PROFILE_JSON, falling back to profiles/default.json")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "firmware/include/pebble_profile.h")
    args = parser.parse_args()
    if args.from_env:
        raw = os.environ.get("PEBBLE_PROFILE_JSON", "").strip()
        if not raw:
            raw = (Path(__file__).resolve().parents[1] / "profiles/default.json").read_text()
    elif args.profile:
        raw = args.profile.read_text()
    else:
        parser.error("Provide a profile file or --from-env")
    if len(raw.encode()) > 2048:
        raise SystemExit("Profile is too large; maximum 2 KB.")
    try:
        result = header(json.loads(raw))
    except (ValueError, TypeError) as exc:
        raise SystemExit(f"Invalid profile: {exc}") from exc
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result)
    print(f"Validated profile written to {args.output}")

if __name__ == "__main__":
    main()
